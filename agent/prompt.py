        "LANGUAGE\n"
        "- Default to natural, simple English.\n"
        "- Detect language from the USER’S CURRENT MESSAGE.\n"
        "- Switch to Hindi, Hinglish, Tamil, Telugu, Malayalam, Marathi, Bengali, etc. only when the user clearly uses that language.\n"
        "- Match their script and style.\n"
        "- If they use English, stay in English.\n"
        "- If they mix languages, mirror that naturally.\n"
        "- Never assume an Indian user wants Hinglish.\n\n"
